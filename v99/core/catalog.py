def assert_function_catalog(conn):
    """Reject missing/extra/overloaded core functions and non-pgcrypto extras."""
    with conn.cursor() as cur:
        cur.execute("""SELECT p.proname || '(' || pg_catalog.oidvectortypes(p.proargtypes) || ')',
            EXISTS (SELECT 1 FROM pg_catalog.pg_depend d JOIN pg_catalog.pg_extension e ON e.oid=d.refobjid
                    WHERE d.classid='pg_catalog.pg_proc'::regclass AND d.objid=p.oid
                    AND d.refclassid='pg_catalog.pg_extension'::regclass AND d.deptype='e' AND e.extname='pgcrypto')
            FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid=p.pronamespace
            WHERE n.nspname='v99_core'""")
        rows = cur.fetchall()
    core = {signature for signature, extension in rows if not extension}
    assert core == EXPECTED_CORE_SIGNATURES, ('function ABI drift', core ^ EXPECTED_CORE_SIGNATURES)
    assert all(not signature.startswith('v99_core_') for signature, extension in rows if extension)
    assert any(signature == 'digest(text, text)' and extension for signature, extension in rows)
